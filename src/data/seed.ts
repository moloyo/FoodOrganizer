import type { Dish, Difficulty, Ingredient } from '../types'

let ingredientCounter = 0

function ing(
  name: string,
  qty = '',
  unit = '',
  category?: string,
): Ingredient {
  ingredientCounter += 1
  return { id: `seed-ing-${ingredientCounter}`, name, qty, unit, category }
}

let dishCounter = 0

/** UUID fijo y válido: Supabase usa uuid como clave y también acepta estos ids al importar. */
function seedDishId(index: number): string {
  return `00000000-0000-4000-8000-${String(index).padStart(12, '0')}`
}

function dish(
  name: string,
  difficulty: Difficulty,
  minutes: number,
  tags: string[],
  steps: string,
  ingredients: Ingredient[],
  options: { freezer?: boolean; favorite?: boolean } = {},
): Dish {
  dishCounter += 1
  return {
    id: seedDishId(dishCounter),
    name,
    difficulty,
    minutes,
    tags,
    steps,
    ingredients,
    freezerFriendly: options.freezer ?? false,
    favorite: options.favorite ?? false,
    sourceUrl: '',
    createdAt: new Date(2026, 0, 1, 12, 0, dishCounter).toISOString(),
  }
}

